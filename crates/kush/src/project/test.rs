//! Test target discovery and entry synthesis.
//!
//! `#[test]` is the only project-level test declaration. The compiler accepts
//! the attribute on functions (and otherwise ignores it), while `kush test`
//! finds those declarations and appends a generated `main` to the test target.
//! The source on disk is never rewritten: the generated entry exists only in the
//! in-memory source passed to the loader for that test process.
use super::{Failure, Project};
use crate::{Span, ast, parser};
use std::fs;

#[derive(Debug, Clone)]
pub struct TestCase {
    pub name: String,
    pub span: Span,
}

impl TestCase {
    pub fn id(&self) -> &str {
        &self.name
    }
}

pub fn target(project: &Project) -> Option<std::path::PathBuf> {
    project.test_target.clone()
}

pub fn discover(
    project: &Project,
    path: &std::path::Path,
) -> Result<(String, Vec<TestCase>), Failure> {
    let name = path.display().to_string();
    let source = fs::read_to_string(path)
        .map_err(|e| Failure::new(format!("cannot read test target {name}: {e}")))?;
    let module = parser::parse(&source)
        .map_err(|diagnostic| Failure::new(diagnostic.render(&name, &source)))?;
    if let Some(first) = module.items.first()
        && let ast::ItemKind::Module(module_path) = &first.item.kind
    {
        let declared = module_path.join(".");
        match project.modules.module_for_file(path) {
            Some(expected) if expected == declared => {}
            Some(expected) => {
                return Err(Failure::new(
                    crate::Diagnostic::new(
                        first.item.span,
                        format!(
                            "test module is declared as '{declared}', but this file maps to '{expected}'"
                        ),
                    )
                    .render(&name, &source),
                ));
            }
            None => {
                return Err(Failure::new(format!(
                    "{name}: test target is not part of the package module index; put it under tests/"
                )));
            }
        }
    }
    let mut tests = Vec::new();
    for declaration in &module.items {
        let ast::ItemKind::Function(function) = &declaration.item.kind else {
            continue;
        };
        if function.name == "main" {
            return Err(Failure::new(
                crate::Diagnostic::new(
                    declaration.item.span,
                    "a test target must not define main(); kush test generates its own entry point",
                )
                .render(&name, &source),
            ));
        }
        if !declaration
            .attributes
            .iter()
            .any(|attribute| attribute.kind == "test")
        {
            continue;
        }
        validate_test(function, declaration.item.span, &name, &source)?;
        tests.push(TestCase {
            name: function.name.clone(),
            span: declaration.item.span,
        });
    }
    Ok((source, tests))
}

fn validate_test(
    function: &ast::Function,
    span: Span,
    name: &str,
    source: &str,
) -> Result<(), Failure> {
    let invalid = if function.total {
        Some("#[test] functions must be executable functions, not 'total fn' logical definitions")
    } else if !function.generics.is_empty() || !function.lifetimes.is_empty() {
        Some("#[test] functions must not be generic or declare lifetime parameters")
    } else if !function.parameters.is_empty() {
        Some("#[test] functions must have no parameters")
    } else if !is_unit(&function.result) {
        Some("#[test] functions must return Unit")
    } else {
        None
    };
    match invalid {
        Some(message) => Err(Failure::new(
            crate::Diagnostic::new(span, message).render(name, source),
        )),
        None => Ok(()),
    }
}

fn is_unit(ty: &ast::Type) -> bool {
    match &ty.kind {
        ast::TypeKind::Named { path, arguments } => {
            arguments.is_empty() && path.len() == 1 && path[0] == "Unit"
        }
        ast::TypeKind::Tuple(parts) => parts.is_empty(),
        _ => false,
    }
}

/// Append a generated entry point after the original source. Appending keeps
/// every existing diagnostic line and column unchanged; the generated text is
/// fully checked like any other source.
pub fn synthesized_source(source: &str, tests: &[TestCase]) -> String {
    let mut out = String::with_capacity(source.len() + 128 + tests.len() * 24);
    out.push_str(source);
    if !source.ends_with('\n') {
        out.push('\n');
    }
    out.push_str("\n// Generated by `kush test` for this run; not written to disk.\n");
    out.push_str("fn main() -> Unit ! {io, alloc, panic, suspend} {\n");
    for test in tests {
        out.push_str("    ");
        out.push_str(&test.name);
        out.push_str("();\n");
    }
    out.push_str("}\n");
    out
}
