//! Declarative adapter generation for `kush bindgen`.
//!
//! A strict `Bridge.toml` names a small checked C ABI adapter: safe Rust
//! function paths, exported C symbols, typed parameters and results, opaque
//! resources, and fallibility. One command generates both sides:
//!
//! * a Rust source file from [`crate::interop::AdapterSpec`] containing the
//!   `extern "C"` shims, panic boundaries, and resource release functions;
//! * a matching public Kush module with the `foreign "symbol" fn ...;`
//!   declarations and `#[foreign("release")]` resource types.
//!
//! The generator never compiles the Kush compiler as a build dependency: it is
//! a command on the existing `kush` binary. The Rust implementation remains
//! ordinary safe Rust; this does not claim arbitrary Rust ABI compatibility.
use crate::interop::{
    AdapterOptions, AdapterSpec, Function, Parameter, Resource, ResultType, Scalar,
};
use std::{
    collections::BTreeSet,
    fmt, fs,
    io::ErrorKind,
    path::{Component, Path, PathBuf},
};
use toml::{Table, Value};

/// Marker used by generated Kush modules so only generated files are replaced.
const KUSH_MARKER: &str = "// @generated by kush bindgen. Do not edit by hand.";
/// Marker emitted by `AdapterSpec` in generated Rust source.
const RUST_MARKER: &str = "// @generated by kush::interop::AdapterSpec. Do not edit by hand.";

const RESERVED_RUNTIME_SYMBOLS: &[&str] = &["kush_bytes_from"];
const RESERVED_RESOURCE_NAMES: &[&str] = &[
    "Bool", "Bytes", "Result", "String", "Unit", "str", "i8", "i16", "i32", "i64", "i128", "isize",
    "u8", "u16", "u32", "u64", "u128", "usize", "f32", "f64",
];
const RESERVED_FUNCTION_NAMES: &[&str] = &["last_error"];

/// One strict generation failure. Messages are user-facing and include the
/// configuration path where useful.
#[derive(Debug, Clone)]
pub struct Error {
    message: String,
}
impl Error {
    fn new(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
        }
    }
}
impl fmt::Display for Error {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(&self.message)
    }
}
impl std::error::Error for Error {}

/// A fully validated pair of generated files, before any filesystem write.
#[derive(Debug, Clone)]
pub struct Generated {
    pub module: String,
    pub rust_path: PathBuf,
    pub kush_path: PathBuf,
    pub rust: String,
    pub kush: String,
    config_dir: PathBuf,
    rust_relative: PathBuf,
    kush_relative: PathBuf,
}

/// Outcome of one `bindgen` invocation.
#[derive(Debug, Clone)]
pub struct Report {
    pub rust_path: PathBuf,
    pub kush_path: PathBuf,
    pub rust_changed: bool,
    pub kush_changed: bool,
    pub check: bool,
}
impl Report {
    pub fn changed(&self) -> bool {
        self.rust_changed || self.kush_changed
    }

    /// Human-readable deterministic summary for the CLI.
    pub fn render(&self) -> String {
        let mut out = String::new();
        for (path, changed) in [
            (&self.rust_path, self.rust_changed),
            (&self.kush_path, self.kush_changed),
        ] {
            if self.check {
                if changed {
                    out.push_str(&format!("would update {}\n", path.display()));
                } else {
                    out.push_str(&format!("up to date {}\n", path.display()));
                }
            } else if changed {
                out.push_str(&format!("Generated {}\n", path.display()));
            } else {
                out.push_str(&format!("Unchanged {}\n", path.display()));
            }
        }
        if self.check && self.changed() {
            out.push_str("bindgen: generated files are out of date\n");
        }
        out
    }
}

/// Read, validate, and render one `Bridge.toml` without touching outputs.
pub fn load(config_path: &Path) -> Result<Generated, Error> {
    let text = fs::read_to_string(config_path).map_err(|error| {
        Error::new(format!(
            "cannot read adapter configuration {}: {error}",
            config_path.display()
        ))
    })?;
    let mut root = text.parse::<Table>().map_err(|error| {
        Error::new(format!(
            "cannot parse adapter configuration {}: {error}",
            config_path.display()
        ))
    })?;

    let adapter_value = root.remove("adapter").ok_or_else(|| {
        Error::new(format!(
            "{}: missing [adapter] table with module, rust-output, and kush-output",
            config_path.display()
        ))
    })?;
    let adapter = as_table(adapter_value, "[adapter]", config_path)?;
    let mut adapter = adapter;
    let module = required_string(&mut adapter, "module", "adapter", config_path)?;
    let rust_relative = required_output(&mut adapter, "rust-output", config_path)?;
    let kush_relative = required_output(&mut adapter, "kush-output", config_path)?;
    reject_unknown(&adapter, "[adapter]", config_path)?;

    validate_module(&module, config_path)?;
    if rust_relative == kush_relative {
        return Err(Error::new(format!(
            "{}: rust-output and kush-output must be different files",
            config_path.display()
        )));
    }

    let mut resources = Vec::new();
    let mut resource_names = BTreeSet::new();
    if let Some(value) = root.remove("resource") {
        for (index, value) in as_array(value, "[[resource]]", config_path)?
            .into_iter()
            .enumerate()
        {
            let table = as_table(value, &format!("resource #{index}"), config_path)?;
            let resource = parse_resource(table, index, config_path)?;
            if !resource_names.insert(resource.name.clone()) {
                return Err(Error::new(format!(
                    "{}: duplicate resource name '{}'",
                    config_path.display(),
                    resource.name
                )));
            }
            if RESERVED_RESOURCE_NAMES.contains(&resource.name.as_str()) {
                return Err(Error::new(format!(
                    "{}: resource name '{}' is reserved by the Kush prelude",
                    config_path.display(),
                    resource.name
                )));
            }
            resources.push(resource);
        }
    }

    let mut functions = Vec::new();
    let mut function_names = BTreeSet::new();
    if let Some(value) = root.remove("function") {
        for (index, value) in as_array(value, "[[function]]", config_path)?
            .into_iter()
            .enumerate()
        {
            let table = as_table(value, &format!("function #{index}"), config_path)?;
            let function = parse_function(table, index, config_path)?;
            if !function_names.insert(function.name.clone()) {
                return Err(Error::new(format!(
                    "{}: duplicate Kush function name '{}'",
                    config_path.display(),
                    function.name
                )));
            }
            if RESERVED_FUNCTION_NAMES.contains(&function.name.as_str()) {
                return Err(Error::new(format!(
                    "{}: function name '{}' is reserved for the generated error accessor",
                    config_path.display(),
                    function.name
                )));
            }
            functions.push(function);
        }
    }
    if functions.is_empty() {
        return Err(Error::new(format!(
            "{}: at least one [[function]] declaration is required",
            config_path.display()
        )));
    }

    reject_unknown(&root, "configuration", config_path)?;

    let support_symbol_prefix = support_prefix(&module);
    let reserved_symbols = [
        format!("{support_symbol_prefix}_last_error"),
        format!("{support_symbol_prefix}_last_error_bytes"),
    ];
    for resource in &resources {
        check_symbol(
            &resource.release_symbol,
            &reserved_symbols,
            "resource release",
            config_path,
        )?;
    }
    for function in &functions {
        check_symbol(&function.symbol, &reserved_symbols, "function", config_path)?;
    }

    let spec = AdapterSpec {
        resources,
        functions,
    };
    spec.validate().map_err(|message| {
        Error::new(format!(
            "{}: invalid adapter configuration: {message}",
            config_path.display()
        ))
    })?;

    let rust = spec
        .generate_with_options(&AdapterOptions::new(support_symbol_prefix.clone()))
        .map_err(|message| {
            Error::new(format!(
                "{}: cannot generate Rust adapter: {message}",
                config_path.display()
            ))
        })?;
    let kush = render_kush(&module, &support_symbol_prefix, &spec);

    let config_dir = config_path
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .map(Path::to_path_buf)
        .unwrap_or_default();
    let rust_path = config_dir.join(&rust_relative);
    let kush_path = config_dir.join(&kush_relative);

    let config_identity = identity(config_path);
    for (field, path) in [("rust-output", &rust_path), ("kush-output", &kush_path)] {
        if identity(path) == config_identity {
            return Err(Error::new(format!(
                "{}: {field} '{}' would overwrite the configuration file",
                config_path.display(),
                path.display()
            )));
        }
    }
    if identity(&rust_path) == identity(&kush_path) {
        return Err(Error::new(format!(
            "{}: rust-output and kush-output resolve to the same file '{}'",
            config_path.display(),
            rust_path.display()
        )));
    }

    Ok(Generated {
        module,
        rust_path,
        kush_path,
        rust,
        kush,
        config_dir,
        rust_relative,
        kush_relative,
    })
}

/// Generate and (unless `check`) write the configured outputs.
///
/// Existing files without the matching generated marker are never replaced.
/// With `check`, nothing is written; the returned report records drift so the
/// caller can exit non-zero.
pub fn run(config_path: &Path, check: bool) -> Result<Report, Error> {
    let generated = load(config_path)?;
    let rust_changed = inspect_output(
        &generated.config_dir,
        &generated.rust_relative,
        &generated.rust_path,
        &generated.rust,
        RUST_MARKER,
    )?;
    let kush_changed = inspect_output(
        &generated.config_dir,
        &generated.kush_relative,
        &generated.kush_path,
        &generated.kush,
        KUSH_MARKER,
    )?;
    let report = Report {
        rust_path: generated.rust_path.clone(),
        kush_path: generated.kush_path.clone(),
        rust_changed,
        kush_changed,
        check,
    };
    if check || !report.changed() {
        return Ok(report);
    }

    if rust_changed {
        write_atomic(
            &generated.config_dir,
            &generated.rust_relative,
            &generated.rust_path,
            &generated.rust,
        )?;
    }
    if kush_changed {
        write_atomic(
            &generated.config_dir,
            &generated.kush_relative,
            &generated.kush_path,
            &generated.kush,
        )?;
    }
    Ok(report)
}

fn parse_resource(mut table: Table, index: usize, path: &Path) -> Result<Resource, Error> {
    let section = format!("[[resource]] #{index}");
    let name = required_string(&mut table, "name", &section, path)?;
    validate_kush_identifier(&name, "resource name", path)?;
    let rust_type = required_string(&mut table, "rust-type", &section, path)?;
    let release_symbol = required_string(&mut table, "release-symbol", &section, path)?;
    reject_unknown(&table, &section, path)?;
    Ok(Resource {
        name,
        rust_type,
        release_symbol,
    })
}

fn parse_function(mut table: Table, index: usize, path: &Path) -> Result<Function, Error> {
    let section = format!("[[function]] #{index}");
    let name = required_string(&mut table, "name", &section, path)?;
    validate_kush_identifier(&name, "function name", path)?;
    let symbol = required_string(&mut table, "symbol", &section, path)?;
    let rust_path = required_string(&mut table, "rust-path", &section, path)?;
    let fallible = match table.remove("fallible") {
        Some(Value::Boolean(value)) => value,
        Some(_) => {
            return Err(field_error(
                path,
                &format!("{section}.fallible"),
                "must be a boolean",
            ));
        }
        None => false,
    };
    let result = match table.remove("result") {
        Some(value) => parse_result(value, &name, path)?,
        None => ResultType::Unit,
    };
    let mut parameters = Vec::new();
    if let Some(value) = table.remove("parameters") {
        for (parameter_index, value) in as_array(value, &format!("{section}.parameters"), path)?
            .into_iter()
            .enumerate()
        {
            parameters.push(parse_parameter(
                value,
                &format!("{section}.parameters[{parameter_index}]"),
                path,
            )?);
        }
    }
    reject_unknown(&table, &section, path)?;
    Ok(Function {
        name,
        symbol,
        rust_path,
        parameters,
        result,
        fallible,
    })
}

fn parse_parameter(value: Value, section: &str, path: &Path) -> Result<Parameter, Error> {
    let mut table = as_table(value, section, path)?;
    let name = required_string(&mut table, "name", section, path)?;
    validate_kush_identifier(&name, "parameter name", path)?;
    let ty = table.remove("type");
    let resource = table.remove("resource");
    reject_unknown(&table, section, path)?;
    match (ty, resource) {
        (Some(Value::String(ty)), None) => match ty.as_str() {
            "text" => Ok(Parameter::Str { name }),
            "bytes" => Ok(Parameter::Bytes { name }),
            _ => parse_scalar(&ty)
                .map(|ty| Parameter::Scalar { name, ty })
                .ok_or_else(|| {
                    field_error(
                        path,
                        &format!("{section}.type"),
                        "must be one of i8, i16, i32, i64, u8, u16, u32, u64, f32, f64, bool, text, bytes",
                    )
                }),
        },
        (None, Some(Value::String(resource))) => Ok(Parameter::Resource { name, resource }),
        (None, Some(_)) => Err(field_error(
            path,
            &format!("{section}.resource"),
            "must be a declared resource name",
        )),
        (Some(_), None) => Err(field_error(
            path,
            &format!("{section}.type"),
            "must be a string type name",
        )),
        (Some(_), Some(_)) => Err(Error::new(format!(
            "{}: {section} must declare exactly one of 'type' or 'resource'",
            path.display()
        ))),
        (None, None) => Err(Error::new(format!(
            "{}: {section} needs a 'type' or 'resource' field",
            path.display()
        ))),
    }
}

fn parse_result(value: Value, function: &str, path: &Path) -> Result<ResultType, Error> {
    match value {
        Value::String(ty) => match ty.as_str() {
            "unit" => Ok(ResultType::Unit),
            "bytes" => Ok(ResultType::Bytes),
            "text" => Err(Error::new(format!(
                "{}: function '{function}' requests an owned text result; return 'bytes' and encode text explicitly",
                path.display()
            ))),
            _ => parse_scalar(&ty)
                .map(ResultType::Scalar)
                .ok_or_else(|| {
                    Error::new(format!(
                        "{}: function '{function}' result must be one of unit, i8, i16, i32, i64, u8, u16, u32, u64, f32, f64, bool, bytes, or {{ resource = \"Name\" }}",
                        path.display()
                    ))
                }),
        },
        Value::Table(mut table) => {
            let resource = match table.remove("resource") {
                Some(Value::String(resource)) => resource,
                Some(_) => {
                    return Err(field_error(
                        path,
                        "result.resource",
                        "must be a declared resource name",
                    ));
                }
                None => {
                    return Err(Error::new(format!(
                        "{}: function '{function}' result table needs a 'resource' field",
                        path.display()
                    )));
                }
            };
            reject_unknown(&table, "result", path)?;
            Ok(ResultType::Resource(resource))
        }
        _ => Err(Error::new(format!(
            "{}: function '{function}' result must be a type string or a {{ resource = \"Name\" }} table",
            path.display()
        ))),
    }
}

fn parse_scalar(name: &str) -> Option<Scalar> {
    Some(match name {
        "i8" => Scalar::I8,
        "i16" => Scalar::I16,
        "i32" => Scalar::I32,
        "i64" => Scalar::I64,
        "u8" => Scalar::U8,
        "u16" => Scalar::U16,
        "u32" => Scalar::U32,
        "u64" => Scalar::U64,
        "f32" => Scalar::F32,
        "f64" => Scalar::F64,
        "bool" => Scalar::Bool,
        _ => return None,
    })
}

fn scalar_kush(ty: Scalar) -> &'static str {
    match ty {
        Scalar::I8 => "i8",
        Scalar::I16 => "i16",
        Scalar::I32 => "i32",
        Scalar::I64 => "i64",
        Scalar::U8 => "u8",
        Scalar::U16 => "u16",
        Scalar::U32 => "u32",
        Scalar::U64 => "u64",
        Scalar::F32 => "f32",
        Scalar::F64 => "f64",
        Scalar::Bool => "Bool",
    }
}

fn kush_result(result: &ResultType, fallible: bool) -> String {
    let value = match result {
        ResultType::Unit => "Unit".to_owned(),
        ResultType::Scalar(ty) => scalar_kush(*ty).to_owned(),
        ResultType::Bytes => "Bytes".to_owned(),
        ResultType::Resource(resource) => resource.clone(),
    };
    if fallible {
        format!("Result<{value}, i64>")
    } else {
        value
    }
}

fn render_kush(module: &str, support_prefix: &str, spec: &AdapterSpec) -> String {
    let mut out = String::new();
    out.push_str(KUSH_MARKER);
    out.push('\n');
    out.push_str(
        "// Trusted boundary: the C ABI is checked on the Kush side; the Rust\n\
         // implementations remain trusted code. Regenerate with `kush bindgen`.\n\
         //\n",
    );
    out.push_str(&format!("module {module};\n\n"));
    out.push_str("use std.result.Result;\n\n");
    for resource in &spec.resources {
        out.push_str(&format!(
            "#[foreign(\"{}\")]\npub struct {} {{}}\n\n",
            resource.release_symbol, resource.name
        ));
    }
    for function in &spec.functions {
        let parameters = function
            .parameters
            .iter()
            .map(|parameter| match parameter {
                Parameter::Scalar { name, ty } => format!("{name}: {}", scalar_kush(*ty)),
                Parameter::Str { name } => format!("{name}: &str"),
                Parameter::Bytes { name } => format!("{name}: &Bytes"),
                Parameter::Resource { name, resource } => format!("{name}: &{resource}"),
            })
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            "pub foreign \"{}\" fn {}({parameters}) -> {} ! {{io}};\n",
            function.symbol,
            function.name,
            kush_result(&function.result, function.fallible)
        ));
    }
    out.push_str(&format!(
        "\npub foreign \"{support_prefix}_last_error_bytes\" fn last_error() -> Result<Bytes, i64> ! {{io}};\n"
    ));
    out
}

fn support_prefix(module: &str) -> String {
    format!("kush_{}_bridge", module.replace('.', "_"))
}

fn validate_module(module: &str, path: &Path) -> Result<(), Error> {
    if module.is_empty() {
        return Err(field_error(path, "adapter.module", "must not be empty"));
    }
    let parts = module.split('.').collect::<Vec<_>>();
    if parts.first() == Some(&"std") {
        return Err(field_error(
            path,
            "adapter.module",
            "must not use the reserved 'std' module prefix",
        ));
    }
    for part in &parts {
        if !crate::project::manifest::valid_module_component(part) {
            return Err(Error::new(format!(
                "{}: adapter.module component '{part}' must be one ASCII Kush identifier and not a keyword",
                path.display()
            )));
        }
    }
    Ok(())
}

fn validate_kush_identifier(name: &str, what: &str, path: &Path) -> Result<(), Error> {
    if !crate::project::manifest::valid_module_component(name) {
        return Err(Error::new(format!(
            "{}: {what} '{name}' must be one ASCII Kush identifier and not a keyword",
            path.display()
        )));
    }
    Ok(())
}

fn check_symbol(
    symbol: &str,
    dynamic_reserved: &[String],
    what: &str,
    path: &Path,
) -> Result<(), Error> {
    if RESERVED_RUNTIME_SYMBOLS.contains(&symbol) || dynamic_reserved.iter().any(|r| r == symbol) {
        return Err(Error::new(format!(
            "{}: {what} symbol '{symbol}' is reserved by the generated bridge support",
            path.display()
        )));
    }
    Ok(())
}

fn required_output(table: &mut Table, field: &str, path: &Path) -> Result<PathBuf, Error> {
    let text = required_string(table, field, "adapter", path)?;
    if text.contains('\0') {
        return Err(field_error(
            path,
            &format!("adapter.{field}"),
            "must not contain NUL bytes",
        ));
    }
    let relative = Path::new(&text);
    if relative.is_absolute() {
        return Err(field_error(
            path,
            &format!("adapter.{field}"),
            "must be relative to the configuration file, not absolute",
        ));
    }
    let mut has_name = false;
    for component in relative.components() {
        match component {
            Component::Normal(_) => has_name = true,
            Component::CurDir => {}
            Component::ParentDir => {
                return Err(field_error(
                    path,
                    &format!("adapter.{field}"),
                    "must stay inside the configuration directory; '..' is not allowed",
                ));
            }
            Component::RootDir | Component::Prefix(_) => {
                return Err(field_error(
                    path,
                    &format!("adapter.{field}"),
                    "must be a relative path",
                ));
            }
        }
    }
    if !has_name {
        return Err(field_error(
            path,
            &format!("adapter.{field}"),
            "must name a file",
        ));
    }
    Ok(relative.to_path_buf())
}

fn required_string(
    table: &mut Table,
    field: &str,
    section: &str,
    path: &Path,
) -> Result<String, Error> {
    match table.remove(field) {
        Some(Value::String(value)) if !value.is_empty() => Ok(value),
        Some(Value::String(_)) => Err(field_error(
            path,
            &format!("{section}.{field}"),
            "must not be empty",
        )),
        Some(_) => Err(field_error(
            path,
            &format!("{section}.{field}"),
            "must be a string",
        )),
        None => Err(field_error(
            path,
            &format!("{section}.{field}"),
            "is required",
        )),
    }
}

fn as_table(value: Value, field: &str, path: &Path) -> Result<Table, Error> {
    match value {
        Value::Table(table) => Ok(table),
        _ => Err(field_error(path, field, "must be a table")),
    }
}

fn as_array(value: Value, field: &str, path: &Path) -> Result<Vec<Value>, Error> {
    match value {
        Value::Array(values) => Ok(values),
        _ => Err(field_error(path, field, "must be an array of tables")),
    }
}

fn reject_unknown(table: &Table, section: &str, path: &Path) -> Result<(), Error> {
    if let Some(key) = table.keys().next() {
        return Err(Error::new(format!(
            "{}: unknown field '{key}' in {section}",
            path.display()
        )));
    }
    Ok(())
}

fn field_error(path: &Path, field: &str, message: &str) -> Error {
    Error::new(format!("{}: {field} {message}", path.display()))
}

fn identity(path: &Path) -> PathBuf {
    if let Ok(canonical) = fs::canonicalize(path) {
        return canonical;
    }
    if let Some(parent) = path.parent()
        && let Ok(canonical) = fs::canonicalize(parent)
        && let Some(name) = path.file_name()
    {
        return canonical.join(name);
    }
    absolute_lexical(path)
}

fn absolute_lexical(path: &Path) -> PathBuf {
    let joined = if path.is_absolute() {
        path.to_path_buf()
    } else {
        std::env::current_dir()
            .unwrap_or_else(|_| PathBuf::from("."))
            .join(path)
    };
    let mut normalized = PathBuf::new();
    for component in joined.components() {
        match component {
            Component::Prefix(prefix) => normalized.push(prefix.as_os_str()),
            Component::RootDir => normalized.push(Component::RootDir.as_os_str()),
            Component::CurDir => {}
            Component::ParentDir => {
                normalized.pop();
            }
            Component::Normal(part) => normalized.push(part),
        }
    }
    normalized
}

/// Return true when the file needs to change. Missing files count as drift.
/// Existing unmarked files are an error rather than a silent overwrite.
fn inspect_output(
    base: &Path,
    relative: &Path,
    path: &Path,
    expected: &str,
    marker: &str,
) -> Result<bool, Error> {
    walk_output(base, relative, false)?;
    match fs::symlink_metadata(path) {
        Ok(metadata) if metadata.file_type().is_symlink() => Err(Error::new(format!(
            "{}: refusing to write through a symbolic link",
            path.display()
        ))),
        Ok(metadata) if !metadata.is_file() => Err(Error::new(format!(
            "{}: generated output must be a regular file",
            path.display()
        ))),
        Ok(_) => {
            let current = fs::read_to_string(path).map_err(|error| {
                Error::new(format!(
                    "cannot read generated output {}: {error}",
                    path.display()
                ))
            })?;
            if !current.starts_with(marker) {
                return Err(Error::new(format!(
                    "{}: refusing to overwrite a file not generated by kush bindgen; move it or remove it explicitly",
                    path.display()
                )));
            }
            Ok(current != expected)
        }
        Err(error) if error.kind() == ErrorKind::NotFound => Ok(true),
        Err(error) => Err(Error::new(format!(
            "cannot inspect generated output {}: {error}",
            path.display()
        ))),
    }
}

fn write_atomic(base: &Path, relative: &Path, path: &Path, contents: &str) -> Result<(), Error> {
    walk_output(base, relative, true)?;
    let parent = path.parent().unwrap_or(base);
    let name = path
        .file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .unwrap_or_else(|| "output".to_owned());
    let temporary = parent.join(format!(".{name}.kush-bindgen-{}", std::process::id()));
    fs::write(&temporary, contents).map_err(|error| {
        Error::new(format!(
            "cannot write temporary output {}: {error}",
            temporary.display()
        ))
    })?;
    if let Err(error) = fs::rename(&temporary, path) {
        let _ = fs::remove_file(&temporary);
        return Err(Error::new(format!(
            "cannot replace generated output {}: {error}",
            path.display()
        )));
    }
    Ok(())
}

/// Check every existing component and optionally create missing directories.
/// Symbolic links are rejected instead of being followed.
fn walk_output(base: &Path, relative: &Path, create: bool) -> Result<(), Error> {
    let components = relative
        .components()
        .filter_map(|component| match component {
            Component::Normal(part) => Some(part.to_os_string()),
            _ => None,
        })
        .collect::<Vec<_>>();
    let mut current = base.to_path_buf();
    for (index, component) in components.iter().enumerate() {
        current.push(component);
        let last = index + 1 == components.len();
        match fs::symlink_metadata(&current) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                return Err(Error::new(format!(
                    "{}: refusing to use a symbolic link in a generated output path",
                    current.display()
                )));
            }
            Ok(metadata) if !last && !metadata.is_dir() => {
                return Err(Error::new(format!(
                    "{}: generated output parent is not a directory",
                    current.display()
                )));
            }
            Ok(metadata) if last && metadata.is_dir() => {
                return Err(Error::new(format!(
                    "{}: generated output path is a directory",
                    current.display()
                )));
            }
            Ok(_) => {}
            Err(error) if error.kind() == ErrorKind::NotFound => {
                if last {
                    return Ok(());
                }
                if create {
                    fs::create_dir(&current).map_err(|error| {
                        Error::new(format!(
                            "cannot create generated output directory {}: {error}",
                            current.display()
                        ))
                    })?;
                } else {
                    // Everything below a missing directory is also missing.
                    return Ok(());
                }
            }
            Err(error) => {
                return Err(Error::new(format!(
                    "cannot inspect generated output path {}: {error}",
                    current.display()
                )));
            }
        }
    }
    Ok(())
}
